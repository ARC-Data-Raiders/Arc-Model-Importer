"""Shipped lighting scenario catalog + on-demand game textures (no FModel dump needed).

``assets/lighting_scenarios.json`` is generated by
``scripts/lighting/build_lighting_catalog.py`` from static pak reads. Textures it
references (LUT strips, sky cloud layers, the exposure meter mask) are pulled
from the user's game install through the bundled extractor into the ArcPak
cache; an FModel dump under the Pioneer root is used when it already has them.
"""
from __future__ import annotations

import json
import os
from typing import Any

import bpy

from ..Shared import utils

_CATALOG: dict[str, Any] | None = None
_ENUM_CACHE = {}
_MAP_ITEMS: list[tuple[str, str, str, int]] = []
_SCENARIO_ITEMS: list[tuple[str, str, str, int]] = []
_LUT_ITEMS: list[tuple[str, str, str, int]] = []
_SKY_ITEMS: list[tuple[str, str, str, int]] = []
NONE = "_NONE_"
LUT_DIR = "/Game/Pioneer/Lighting/LUTs/"
# Linear (SRGB=False) sky textures; everything else in the catalog is sRGB.
_LINEAR_SKY = {"hdri_sky_013", "hdri_sky_029_8K_Sphere", "hdri_sky_046", "hdri_sky_072_8K_Sphere", "hdri_sky_098",
               "hdri_sky_124", "VHDRI_Twilight_Stormy02", "VHDRI_Twilight_Stormy03", "HFD_HemiClouds06_01"}


STUDIO_MAP = "MainMenu"  # authored studio rigs are listed as extra Main Menu scenarios
STUDIO_PREFIX = "STUDIO:"


def studio_rig_id(tag: str) -> str:
    return tag[len(STUDIO_PREFIX):] if (tag or "").startswith(STUDIO_PREFIX) else ""


def catalog_path() -> str:
    return os.path.join(os.path.dirname(os.path.dirname(__file__)), "assets", "lighting_scenarios.json")


def load_catalog(force: bool = False) -> dict[str, Any]:
    global _CATALOG
    if _CATALOG is None or force:
        _ENUM_CACHE.clear()
        try:
            with open(catalog_path(), "r", encoding="utf-8") as fh:
                _CATALOG = json.load(fh)
        except (OSError, json.JSONDecodeError) as exc:
            print(f"Arc Lighting: catalog unavailable ({exc})")
            _CATALOG = {"maps": {}, "curves": {}}
    return _CATALOG


def map_ids() -> list[str]:
    return list(load_catalog().get("maps", {}))


def scenario(map_id: str, tag: str) -> dict[str, Any] | None:
    entry = load_catalog().get("maps", {}).get(map_id or "", {})
    return (entry.get("scenarios") or {}).get(tag or "")


def default_map(scene) -> str:
    placed = getattr(scene, "arc_placement_map", "") or ""
    for mid in map_ids():
        if placed and (placed == mid or placed.startswith(mid.split("_")[0])):
            return mid
    return ""


def make_lighting_map_items(self, context):
    del self, context
    load_catalog()
    cache_key = ('maps',)
    if cache_key in _ENUM_CACHE:
        return _ENUM_CACHE[cache_key]
    items = [(NONE, "Select Map...", "Arc Raiders map whose lighting scenarios to use", 0)]
    for i, (mid, entry) in enumerate(load_catalog().get("maps", {}).items(), start=1):
        count = len(entry.get("scenarios") or {})
        items.append((mid, entry.get("label") or mid, f"{mid}: {count} lighting scenarios", i))
    _ENUM_CACHE[cache_key] = items
    return items


def make_lighting_scenario_items(self, context):
    del self
    scene = getattr(context, "scene", None)
    map_id = getattr(scene, "arc_lighting_map", "") if scene is not None else ""
    entry = load_catalog().get("maps", {}).get(map_id or "", {})
    scen = entry.get("scenarios") or {}
    load_catalog()
    cache_key = ('scenarios', map_id)
    if cache_key in _ENUM_CACHE:
        return _ENUM_CACHE[cache_key]
    items = [(NONE, "Select Scenario..." if scen else "Pick a map above", "Gameplay lighting scenario", 0)]
    total = sum(float(s.get("weight") or 0.0) for s in scen.values())
    for i, (tag, s) in enumerate(scen.items(), start=1):
        weight = float(s.get("weight") or 0.0)
        share = f" · {100.0 * weight / total:.0f}% of raids" if total > 0 and weight > 0 else ""
        items.append((tag, s.get("label") or tag, f"{tag}{share}", i))
    if map_id == STUDIO_MAP:
        from . import studio_lights
        for j, (rid, rig) in enumerate(studio_lights.rigs().items(), start=len(items)):
            items.append((STUDIO_PREFIX + rid, str(rig.get("label") or rid),
                          f"Authored studio light rig ({len(rig['lights'])} lights), imported exactly", j))
    _ENUM_CACHE[cache_key] = items
    return items


def lut_names() -> list[str]:
    names = set()
    for entry in load_catalog().get("maps", {}).values():
        for s in (entry.get("scenarios") or {}).values():
            for vol in s.get("volumes") or []:
                ref = (vol.get("overrides") or {}).get("ColorGradingLUT")
                if isinstance(ref, dict) and ref.get("name"):
                    names.add(ref["name"])
    names.update(load_catalog().get("extra_luts") or [])
    return sorted(names)


def make_lighting_look_items(self, context):
    del self, context
    load_catalog()
    cache_key = ('luts',)
    if cache_key in _ENUM_CACHE:
        return _ENUM_CACHE[cache_key]
    items = [(NONE, "(scenario LUT)", "Use the scenario's own ColorGradingLUT", 0)]
    for i, name in enumerate(lut_names(), start=1):
        label = name.replace("RGBTable16x1_Kodak5218", "Kodak 5218").replace("_", " ").strip() or name
        items.append((name, label, f"{LUT_DIR}{name}", i))
    _ENUM_CACHE[cache_key] = items
    return items


def sky_texture_refs() -> dict[str, str]:
    refs = {}
    for entry in load_catalog().get("maps", {}).values():
        for s in (entry.get("scenarios") or {}).values():
            ref = (s.get("sky") or {}).get("Cloud Wisps Texture")
            if isinstance(ref, dict) and ref.get("name"):
                refs[ref["name"]] = ref.get("path") or ""
            mid = s.get("sky_material") or {}
            path = (mid.get("texture_paths") or {}).get("Cloud_Wisps_Texture")
            name = (mid.get("textures") or {}).get("Cloud_Wisps_Texture")
            if path and name:
                refs.setdefault(name, path)
    return dict(sorted(refs.items()))


def make_lighting_hdri_items(self, context):
    del self, context
    load_catalog()
    cache_key = ('skies',)
    if cache_key in _ENUM_CACHE:
        return _ENUM_CACHE[cache_key]
    items = [(NONE, "(scenario clouds)", "Use the scenario's own cloud layer texture", 0)]
    for i, (name, path) in enumerate(sky_texture_refs().items(), start=1):
        items.append((name, name.replace("_", " "), path, i))
    _ENUM_CACHE[cache_key] = items
    return items


