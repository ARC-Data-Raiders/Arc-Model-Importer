def _object_path(path: str) -> str:
    text = (path or "").split(".", 1)[0]
    return text if text.startswith("/") else "/" + text


def _cooked(path: str) -> str:
    text = _object_path(path)
    if text.startswith("/Game/"):
        return "PioneerGame/Content/" + text[len("/Game/"):]
    return text.lstrip("/")


def _candidates(path: str) -> list[str]:
    from ..Shared import pak_extract

    rel = _cooked(path)
    out = [os.path.join(pak_extract.cache_dir(), *rel.split("/")) + ".png"]
    if rel.startswith("PioneerGame/Content/"):
        # The bundled pak index mounts some packages under the remapped plugin root.
        remapped = "RemappedPlugins/Content/" + rel[len("PioneerGame/Content/"):]
        out.append(os.path.join(pak_extract.cache_dir(), *remapped.split("/")) + ".png")
    pioneer = utils.get_pioneer_root()
    if pioneer and rel.startswith("PioneerGame/Content/Pioneer/"):
        out.append(os.path.join(pioneer, *rel[len("PioneerGame/Content/Pioneer/"):].split("/")) + ".png")
    return out


def find_texture(path: str) -> str:
    for cand in _candidates(path):
        if os.path.isfile(cand):
            return cand
    return ""


def ensure_textures(scene, paths: list[str]) -> tuple[dict[str, str], str]:
    """Resolve object paths to PNG files, extracting missing ones from the paks."""
    from ..Shared import pak_extract

    found = {p: find_texture(p) for p in paths if p}
    missing = [p for p, f in found.items() if not f]
    note = ""
    if missing:
        game = pak_extract.configured_dir(scene)
        usmap = pak_extract.resolve_usmap(scene)
        if not game or not usmap:
            note = "set the game folder in Settings to fetch lighting textures"
        else:
            try:
                code, log, _ = pak_extract.extract_paths(game, usmap, [_cooked(p) for p in missing])
                if code != 0:
                    note = f"texture extraction exited {code}"
                    print(f"Arc Lighting: extraction log tail:\n{log[-1200:]}")
            except Exception as exc:
                note = f"texture extraction failed: {exc}"
            for p in missing:
                found[p] = find_texture(p)
            still = [p.rsplit("/", 1)[-1] for p in missing if not found[p]]
            if still:
                note = (note + "; " if note else "") + "not extracted: " + ", ".join(still)
    return found, note


def lut_path(name: str) -> str:
    return LUT_DIR + name


def load_strip(png: str):
    """RGBTable16x1 PNG -> float RGBA strip, top row first (texture v = 0)."""
    import numpy as np

    img = bpy.data.images.load(png, check_existing=False)
    try:
        img.colorspace_settings.name = "Non-Color"
        img.alpha_mode = "CHANNEL_PACKED"
        w, h = img.size
        px = np.empty(w * h * 4, dtype=np.float32)
        img.pixels.foreach_get(px)
    finally:
        bpy.data.images.remove(img)
    if (w, h) != (256, 16):
        raise ValueError(f"{os.path.basename(png)} is {w}x{h}, expected a 256x16 RGBTable16x1 strip")
    # Exact 8-bit texel values, as the GPU would fetch them.
    px = np.round(px * 255.0) / 255.0
    return px.reshape(h, w, 4)[::-1].astype(np.float32).copy()


def load_sky_image(png: str, name: str) -> bpy.types.Image:
    img = next((i for i in bpy.data.images if i.get("arc_lighting_sky_source") == png), None)
    if img is None:
        img = bpy.data.images.load(png, check_existing=False)
        img["arc_lighting_sky_source"] = png
    img.colorspace_settings.name = "Non-Color" if name in _LINEAR_SKY else "sRGB"
    return img


def load_mask_image(png: str) -> bpy.types.Image:
    img = next((i for i in bpy.data.images if i.get("arc_lighting_mask_source") == png), None)
    if img is None:
        img = bpy.data.images.load(png, check_existing=False)
        img["arc_lighting_mask_source"] = png
    img.colorspace_settings.name = "Non-Color"
    return img
