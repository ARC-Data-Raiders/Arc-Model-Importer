        m=_paint_metal(metal,scalar(record,'Base - Metalness Tweak - '+zone,0.),target,visibility)
        rough_tweak=color(record,'Base - Roughness Tweak - '+zone,(0.,0.,0.))
        rr=lerp(rough,_paint_rough(rough,rough_tweak,target,wa,roughpop),visibility)
        if mid_visibility is not None:
            # Same instr ranges 310-323 (colour), 405-411 (metal), 457-464 (roughness).
            mt=scalar(record,'Mid Layer - Surface Type - '+zone,1.)
            c=lerp(c,_paint_color(c,color(record,'Mid Layer - Color - '+zone),mt,wa2,pop),mid_visibility)
            m=_paint_metal(m,scalar(record,'Mid Layer - Metallic Tweak - '+zone,1.),mt,mid_visibility)
            rr=lerp(rr,_paint_rough(rr,color(record,'Mid Layer - Roughness Tweak - '+zone,(0.,0.,0.)),mt,wa,roughpop),mid_visibility)
        if pattern_visibility is not None:
            pt=scalar(record,'Pattern - Surface Type - '+zone,1.)
            c=lerp(c,_paint_color(c,pattern,pt,wa2,pop),pattern_visibility)
            m=_paint_metal(m,scalar(record,'Pattern - Metallic Tweak - '+zone,0.),pt,pattern_visibility)
            pr=_paint_rough(rr,color(record,'Pattern - Roughness Tweak - '+zone,(0.,0.,0.)),pt,wa,roughpop)
            offsets=expr('combine',scalar(record,'Pattern Roughness Offset - R',0.),scalar(record,'Pattern Roughness Offset - G',0.),scalar(record,'Pattern Roughness Offset - B',0.))
            pr=saturate(add(pr,expr('dot',pattern,offsets)))
