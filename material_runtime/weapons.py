    if record.switches.get('Use Paint Thickness',False):diagnostics.append('unsupported_transport:paint-thickness vertex/derivative stage')
    outputs={'base_color':albedo,'normal':normal_out,'metallic':metal,'roughness':rough,'alpha':literal(1.)}
    glare=native_weapon_glare(record,context,diagnostics)
