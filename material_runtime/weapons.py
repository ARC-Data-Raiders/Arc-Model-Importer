def _near(value,target,tolerance):
    return sub(1.,expr('greater_than',expr('abs',sub(value,target)),tolerance))
def _ge(value,threshold):return sub(1.,expr('less_than',value,threshold))
def _guarded_power(value,power):
    return mul(expr('power',expr('max',value,1e-30),power),expr('greater_than',value,0.))
def _surface_type(original,target,mode):
    # Native thresholds are epsilon-guarded, so exact boundary values retain input.
    high=lerp(original,target,mul(sub(1.,_ge(original,.25)),sub(1.,_near(original,.25,.00001))))
    low=lerp(original,target,mul(_ge(original,.25),sub(1.,_near(original,.25,.00001))))
    out=lerp(original,high,mul(_ge(mode,.15),sub(1.,_near(mode,.15,.00001))))
    out=lerp(out,low,mul(_ge(mode,.5),sub(1.,_near(mode,.5,.00001))))
    return lerp(out,target,mul(_ge(mode,.8),sub(1.,_near(mode,.8,.00001))))
def _wear_resistance(wear,delay,resistance,surface):
    visibility=saturate(expr('divide',wear,sub(1.,expr('clamp',delay,0.,.99))))
    return lerp(add(visibility,mul(sub(1.,visibility),resistance)),1.,_near(surface,.5,.02))
def _native_rnm_raw(base,detail):
    t=expr('combine',ch(base,0),ch(base,1),add(ch(base,2),1.))
    u=expr('combine',sub(0.,ch(detail,0)),sub(0.,ch(detail,1)),ch(detail,2))
    return sub(expr('vector_scale',t,expr('dot',t,u)),expr('vector_scale',u,ch(t,2)))
# Stencil paint reads less saturated than in-game captures (bench/paint_chroma_compare.py, 5 stencils: game/ours
# Lab chroma median 1.33). Paint colours only (palettes and pattern), linear light, so bare metal keeps its calibration.
# Linear gain after the saturation. Kept 1: captures are brighter on bare metal too (inspect-screen lighting).
PAINT_SATURATION=1.5
PAINT_VALUE=1.0
def _saturate_paint(c):
    lum=expr('dot',c,expr('combine',.2126,.7152,.0722))
    return mul(expr('max',add(lum,mul(sub(c,lum),PAINT_SATURATION)),0.),PAINT_VALUE)
def _paint_color(under,palette,surface,wear_alpha,pop):
    palette=_saturate_paint(palette)
    physical=lerp(palette,lerp(mul(palette,palette),palette,wear_alpha),pop)
    tint=saturate(mul(mul(under,palette),2.))
    return lerp(tint,physical,mul(_ge(surface,.5),sub(1.,_near(surface,.5,.02))))
def _paint_metal(under,tweak,surface,visibility):
    high=lerp(under,tweak,saturate(mul(visibility,1.5)))
    low=saturate(add(under,tweak))
    return mul(lerp(low,high,_ge(surface,.5)),sub(1.,_near(surface,.5,.02)))
def _paint_rough(under,tweak,surface,wear_alpha,pop):
    high=saturate(add(mul(expr('abs',sub(wear_alpha,.5)),pop),ch(tweak,0)))
    low=mul(under,ch(tweak,2))
    middle=lerp(under,1.,ch(tweak,1))
    return lerp(lerp(low,high,_ge(surface,.5)),middle,_near(surface,.5,.02))
def _quarter_round(value):
    # Exact round_ne(value*4)*.25 thresholds, including even ties.
    return mul(add(add(expr('greater_than',value,.125),_ge(value,.375)),add(expr('greater_than',value,.625),_ge(value,.875))),.25)


def native_weapon_glare(record,context,diagnostics):
    """Native positive sine glare after runtime primitive projection is supplied."""
    if not record.switches.get('Use "Glare"',False):return None
    enabled=record.scalars.get('Use Glare',0.)
    if enabled==0.:return literal((0.,0.,0.))
    coordinate=context.get('weapon_glare_coordinate')
    if coordinate is None:
        diagnostics.append('unsupported_transport:native weapon world-position/primitive glare coordinate')
        return None
    if not context.get('weapon_glare_evidence'):raise ValueError('weapon glare coordinate requires native primitive binding evidence')
    time=context.get('weapon_glare_time',expr('time'))
    frequency=scalar(record,'Frequency',7.)
    phase=expr('divide',add(coordinate,mul(time,scalar(record,'Speed',2.))),expr('max',frequency,1e-12))
    signed=mul(expr('fract',expr('abs',phase)),sub(1.,mul(expr('less_than',phase,0.),2.)))
    phase=mul(signed,frequency)
    phase=mul(phase,sub(1.,mul(_ge(phase,1.),sub(1.,_near(phase,1.,.00001)))))
    wave=saturate(_guarded_power(expr('sin',mul(phase,6.283185)),scalar(record,'Size Reduction',2.)))
    distance=float(record.scalars.get('Distance',8.));rounded=round(distance)
    native_distance=mul(expr('camera_distance'),float(context.get('unreal_units_per_scene_unit',100.)))
    if rounded>0:
        falloff=mul(saturate(expr('power',expr('divide',native_distance,rounded*128.),8.)),min(max(rounded,0.),1.))
    else:
        diagnostics.append('unsupported_native_stage:nonpositive glare Distance reciprocal');return None
    exposure=context.get('weapon_eye_adaptation',literal(1.))
    if 'weapon_eye_adaptation' not in context:diagnostics.append('unsupported_transport:weapon glare eye adaptation; using neutral exposure')
    fx=context.get('weapon_fx_emission_multiplier',literal(1.))
    if 'weapon_fx_emission_multiplier' not in context:diagnostics.append('unsupported_transport:weapon FX global emission multiplier; using neutral multiplier')
    glow=mul(mul(color(record,'Tint Color',(.760525,.814847,.838799)),wave),scalar(record,'Emissive Power',3.))
    glow=mul(mul(glow,sub(1.,falloff)),mul(enabled,fx))
    return tag(expr('max',expr('divide',glow,expr('max',exposure,1e-12)),0.),'DR.Light','Native weapon projected glare')

def compile_native_weapon_paint(record,context=None):
    """Fresh5FD2...0252/8E718...0288 semantic paint/wear stages.

    Static unsupported variants remain diagnostics; no old shader flow is reused.
    """
    context=context or {};diagnostics=[]
    # The pattern mask only recolours zones with Pattern - Use on (master defaults all off); with none on it compiles out.
    patterned=any(record.switches.get('Enable '+z+' Mask',False) and record.switches.get('Pattern - Use - '+z,False) for z in ZONES)
    unsupported=[k for k in ('Use Paintjob Pattern Mask','Use Triplanar Pattern') if record.switches.get(k,False) and (patterned or k!='Use Paintjob Pattern Mask')]
    # Mid layer + pattern in one zone composes base -> mid -> pattern (Tortoiseshell references: pattern over the mid layer).
    if unsupported:return plan(record,'weapon',{},tuple('unsupported_native_stage:paint permutation '+k for k in unsupported))
    nxm=texture(record,'NXM','data');cr=texture(record,'CR','color');crd=texture(record,'CR','data')
    ids=texture(record,'Weapon ID','data');wear=texture(record,'Wear','data')
    quality=context.get('weapon_detail_amount')
    if quality is None:quality=weapon_wear_input()
    quality=saturate(quality)
    raw_wear=mul(mul(saturate(mul(add(sub(scalar(record,'Value PaintMask',0.),expr('min',quality,.8)),ch(wear,1)),2.)),saturate(sub(1.,ch(wear,0)))),2.)
    raw_wear=tag(raw_wear,'DR.Wear','Native wear resistance input')
    # Cooked PS census (33 pattern MIs): the pattern samples UV1 unless 'Use Default UV' is on; 'Use UV1' does not decide it.
    pattern_uv=mul(add(expr('uv',index=0 if record.switches.get('Use Default UV',False) else 1),expr('combine',scalar(record,'Paintjob - uOffset',1.),scalar(record,'Paintjob - vOffset',1.),0.)),expr('combine',mul(scalar(record,'Paintjob - uTiling',1.),scalar(record,'Paintjob - masterTiling',1.)),mul(scalar(record,'Paintjob - vTiling',1.),scalar(record,'Paintjob - masterTiling',1.)),1.))
    pattern=rgb(texture(record,'Paintjob Pattern','color',pattern_uv,default=(1.,1.,1.,1.)))
    # A _CA pattern's alpha is its coverage (Tortoise_02_CA has white RGB where alpha is 0); opaque patterns read 1.
    pattern_alpha=ch(texture(record,'Paintjob Pattern','data',pattern_uv,default=(1.,1.,1.,1.)),3)
    black_mask=literal(1.)
    if record.switches.get('Use Black as Alpha',False):
        maximum=expr('max',expr('max',ch(pattern,0),ch(pattern,1)),ch(pattern,2))
        feather=record.scalars.get('Black Feather',0.)
        if feather==0.:
            black_mask=_ge(maximum,scalar(record,'Black Threshold',.05))
            diagnostics.append('native_limit:zero Black Feather uses hard threshold; equality GPU NaN is undefined')
        else:black_mask=sub(1.,saturate(expr('divide',sub(scalar(record,'Black Threshold',.05),maximum),feather)))
    surface=ch(nxm,2);base_surface=surface
    zone_stages=[]
    for i,zone in enumerate(ZONES):
        if not record.switches.get('Enable '+zone+' Mask',False):continue
        weight=saturate(_guarded_power(ch(ids,_zone_channel(record,i)),2.))
        target=_surface_type(surface,scalar(record,'Base - Surface Type - '+zone,1.),scalar(record,'Base - Surface Type Override Mode - '+zone,1.))
        visibility=_wear_resistance(raw_wear,scalar(record,'Base - Wear Delay',0.),scalar(record,'Base - Wear Resistance - '+zone,0.),target)
        new_surface=lerp(surface,target,visibility)
        mid_visibility=None
        if record.switches.get('Mid Layer - Use - '+zone,False):
            # Bettina PS 18666AC6 instr 97-109: sat(raw*(1+2c)-c), then the base delay/resistance form.
            contrast=scalar(record,'Mid Layer - Mask Contrast - '+zone,0.)
            mid_raw=saturate(sub(mul(raw_wear,add(1.,mul(contrast,2.))),contrast))
            mid_target=scalar(record,'Mid Layer - Surface Type - '+zone,1.)
            mid_visibility=_wear_resistance(mid_raw,scalar(record,'Mid Layer - Wear Delay',0.),scalar(record,'Mid Layer - Wear Resistance - '+zone,0.),mid_target)
            new_surface=lerp(new_surface,mid_target,mid_visibility)
        pattern_visibility=None
        if record.switches.get('Pattern - Use - '+zone,False):
            pattern_target=scalar(record,'Pattern - Surface Type - '+zone,1.)
            # Tortoiseshell PS 51BC9205 instr 102: pattern alpha scales the raw wear before delay/resistance.
            pattern_visibility=_wear_resistance(mul(mul(raw_wear,black_mask),pattern_alpha),scalar(record,'Pattern - Wear Delay',0.),scalar(record,'Pattern - Wear Resistance - '+zone,0.),pattern_target)
            new_surface=lerp(new_surface,pattern_target,pattern_visibility)
        zone_stages.append((zone,weight,target,visibility,mid_visibility,pattern_visibility))
        surface=lerp(surface,new_surface,weight)
    surface=tag(surface,'DR.LayerInputs','Native authored surface styles')
    detail=native_weapon_detail(record,nxm,context,surface)
    normal_base=expr('normal_decode',nxm);detail_n=expr('normal_decode',detail)
    strength=mul(expr('clamp',quality,.2,.5),mul(scalar(record,'Detail N Intensity',1.),2.))
    detail_n=expr('combine',mul(ch(detail_n,0),strength),mul(ch(detail_n,1),strength),ch(detail_n,2))
    composed=_native_rnm_raw(normal_base,detail_n)
    rust_uv=uv(scalar(record,'Rust Tiling',.5),index=1)
    rust_n_tex=expr('texture',reference=context.get('weapon_rust_normal_reference',RUST_NORMAL),role='data',uv=rust_uv)
    rust_n=expr('normal_decode',rust_n_tex)
    rust_composed=_native_rnm_raw(composed,rust_n)
    rust_curve=sub(1.,mul(_quarter_round(quality),.75))
    rust_low=sub(1.,mul(rust_curve,.5))
    rust_exponent=mul(add(mul(rust_curve,.75),.25),1.5)
    rust=saturate(sub(mul(_guarded_power(ch(wear,2),rust_exponent),add(1.,mul(rust_low,2.))),rust_low))
