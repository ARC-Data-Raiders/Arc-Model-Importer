def _zone_channel(record,index):
    leaf=str(record.package or '').replace('\\','/').rsplit('/',1)[-1].split('.',1)[0].casefold()
    return 'RGBA'.index(_ZONE_ID_CHANNELS.get(leaf,'RGBA')[index])

RARITY_SKIN_SWITCHES=('Enable Skin Common','Enable Skin Rare','Enable Skin Epic','Enable Skin Legendary')

def weapon_wear_input():
    return expr('channel',expr('attribute',name=WEAR_PROPERTY,type='OBJECT'),index=0)

def wear_visibility(wear,quality,delay=0.,resistance=0.):
    """Portable monotonic wear policy, explicitly distinct from native shader math."""
    return tag(saturate(add(sub(quality,mul(wear,sub(1.,resistance))),delay)),'DR.Wear','Portable quality wear visibility')

def _pattern_uv(record):
    # Cooked PS census: the pattern samples UV1 unless 'Use Default UV' is on ('Use UV1' does not decide it).
    index=0 if record.switches.get('Use Default UV',False) else 1
    base=expr('uv',index=index)
    scale=expr('combine',mul(scalar(record,'Paintjob - uTiling',1.),scalar(record,'Paintjob - masterTiling',1.)),mul(scalar(record,'Paintjob - vTiling',1.),scalar(record,'Paintjob - masterTiling',1.)),1.)
    return add(mul(base,scale),expr('combine',scalar(record,'Paintjob - uOffset',0.),scalar(record,'Paintjob - vOffset',0.),0.))

def compile_portable_weapon(record,context=None):
    context=context or {};diagnostics=[]
    cr=texture(record,'CR','color',default=(.5,.5,.5,1.))
    outputs={'base_color':rgb(cr),'roughness':literal(.5),'metallic':literal(0.),'alpha':literal(1.)}
    for role,out in (('weapon_roughness','roughness'),('weapon_metallic','metallic'),('weapon_alpha','alpha')):
        value=mapped_channel(record,context,role)
        if value is not None:outputs[out]=value
    if 'NXM' in record.textures:outputs['normal']=normal(record,'NXM')
    elif 'NOM' in record.textures:outputs['normal']=normal(record,'NOM')
    if 'Weapon ID' in record.textures:
        ids=texture(record,'Weapon ID');coords=_pattern_uv(record)
        pattern=texture(record,'Paintjob Pattern','color',coords,default=(1.,1.,1.,1.))
        pattern_ids=texture(record,'Paintjob Pattern Mask','data',coords,default=(1.,0.,0.,0.))
        quality=scalar(record,'WeaponQualitySlider',1.)
        for i,zone in enumerate(ZONES):
            if not record.switches.get('Enable '+zone+' Mask',False):continue
            weight=saturate(ch(ids,i))
            c=color(record,'Base - Color - '+zone)
            if record.switches.get('Mid Layer - Use - '+zone,False):
                binding=(context.get('weapon_layer_masks',{})).get('mid_'+zone)
                if binding is None:diagnostics.append('unsupported_native_stage:Mid Layer '+zone+' mask')
                else:
                    if not context.get('weapon_layer_evidence'):raise ValueError('weapon layer masks require native evidence')
                    c=lerp(c,color(record,'Mid Layer - Color - '+zone),binding)
            if record.switches.get('Pattern - Use - '+zone,False):
                pc=rgb(pattern)
                if record.switches.get('Use Paintjob Pattern Mask',False):
                    pc=color(record,'Paintjob Patern - Black',(0.,0.,0.))
                    for j,z in enumerate(ZONES[:3]):pc=lerp(pc,color(record,'Paintjob Patern - '+z),saturate(ch(pattern_ids,j)))
                if record.switches.get('Set ID Specific Pattern Color - '+zone,False):pc=mul(pc,color(record,'Specific Pattern Color - '+zone))
                c=mul(c,pc)
            if record.switches.get('UseWeaponQuality',False):
                if context.get('portable_weapon_wear',False):
                    wear=ch(texture(record,'Wear'),0)
                    weight=mul(weight,wear_visibility(wear,quality,scalar(record,'Base - Wear Delay',0.),scalar(record,'Base - Wear Resistance - '+zone,0.)))
                    diagnostics.append('portable_weapon_wear:'+zone+' independent preview policy')
                else:diagnostics.append('unsupported_native_stage:native WeaponQuality/Wear transfer '+zone)
            outputs['base_color']=tag(lerp(outputs['base_color'],c,weight),'DR.Surface','Paint zone '+zone)
        diagnostics.append('portable_weapon_palette:authored ID zones and switches; native color-layer blend transfer unproven')
    if record.switches.get('Use Opacity',False):
        outputs['alpha']=saturate(mul(ch(texture(record,'Opacity',default=(1.,1.,1.,1.)),0),scalar(record,'MasterOpacityMultiply',1.)))
    emission=mapped_channel(record,context,'weapon_emission')
    if emission is not None:
        outputs['emission']=tag(mul(color(record,'Tint Color'),emission),'DR.Light','Bound weapon emission')
        outputs['emission_strength']=scalar(record,'Emissive Power',3.)
    if record.switches.get('Use "Glare"',False):diagnostics.append('unsupported_native_stage:weapon glare animation')
    diagnostics+=['unsupported_native_stage:weapon native packed roughness/metal/AO roles']
    diagnostics+=list(unresolved(record,('Use Paint Thickness','Use Triplanar Pattern')))
    # CR+NOM rarity skin stages compile out unless their static switch is on; no
    # shipped weapon MI enables one (cooked shader maps bind only NOM and CR).
    rarity={'Skin Masks':RARITY_SKIN_SWITCHES,'Epic Skin Texture':('Enable Skin Epic',),'Legendary Skin Texture':('Enable Skin Legendary',)}
    diagnostics+=['unsupported_native_stage:'+name for name,gates in rarity.items() if any(record.switches.get(g,False) for g in gates)]
    return plan(record,'weapon',outputs,diagnostics)


WEAPON_DETAIL_ARRAY='/Game/Pioneer/MaterialLibrary/Textures/Weapons/Details/TA_Weapon_Detail_01'

def native_weapon_detail(record,nxm,context,surface_type=None):
    """Expand native array selection to authored static, data-role samples.

    The native layer coordinate is NXM.B*3; no suffix-based layer guessing.
    Ties use nearest-even, while interpolated values select the closest layer.
    """
    coords=uv(scalar(record,'Detail Tiling',.25),index=1)
    reference=context.get('weapon_detail_array_reference',WEAPON_DETAIL_ARRAY)
    count=int(context.get('weapon_detail_layer_count',3))
    if count<1:raise ValueError('weapon detail array must have at least one native layer')
    layers=[expr('texture',reference=reference,role='data',uv=coords,slice=i,stage='DR.Source',name='Weapon detail layer '+str(i)) for i in range(count)]
    index=mul(ch(nxm,2) if surface_type is None else surface_type,3.)
    selected=layers[0]
    for i in range(1,count):
        threshold=i-.5
        choose=expr('greater_than',index,threshold) if i%2 else sub(1.,expr('less_than',index,threshold))
        selected=lerp(selected,layers[i],choose)
    return selected

def compile_weapon(record,context=None):
    context=context or {}
    if context.get('portable_weapon_palette',False):return compile_portable_weapon(record,context)
    if not record.switches.get('UseWeaponQuality',False) and 'weapon_detail_amount' not in context:
        # Without UseWeaponQuality the cooked PS reads quality from the material's
        # WeaponQualitySlider_PREVIEW, not CPD1 (Anvil Ascended_Base_A map D9582171:
        # cb0.w = Value PaintMask - min(PREVIEW,.8), cb1.z = clamp(PREVIEW,.2,.5)*Detail N).
        context=dict(context,weapon_detail_amount=literal(float(record.scalars.get('WeaponQualitySlider_PREVIEW',0.))))
    # This exact stage is native-backed only for the NXX+WPO+ID master. Other
    # weapon masters retain their working profile until their own proof is read.
    if 'NXM' not in record.textures:
        return plan(record,'weapon',{},('unsupported_native_stage:weapon master requires its own packed-channel proof',))
    diagnostics=[]
    nxm=texture(record,'NXM','data',default=(.5,.5,0.,0.))
    cr=texture(record,'CR','color',default=(.5,.5,.5,1.))
    cr_data=texture(record,'CR','data',default=(.5,.5,.5,1.))
    detail=native_weapon_detail(record,nxm,context)
    amount=context.get('weapon_detail_amount')
    if amount is None:amount=weapon_wear_input()
    amount=saturate(amount)
    strength=mul(expr('clamp',amount,.2,.5),mul(scalar(record,'Detail N Intensity',1.),2.))
    base=expr('normal_decode',nxm)
    dn=expr('normal_decode',detail)
    dn=expr('combine',mul(ch(dn,0),strength),mul(ch(dn,1),strength),ch(dn,2))
    composed=tag(expr('rnm',base,dn),'DR.Details','Native selected weapon detail normal')
    c=tag(saturate(mul(rgb(cr),ch(detail,2))),'DR.Surface','Native weapon detail albedo')
    alpha=ch(cr_data,3)
    rough=mul(expr('power',expr('max',alpha,1e-30),1.1),expr('greater_than',alpha,0.))
    adjusted=saturate(add(rough,mul(scalar(record,'Detail R Intensity',1.),sub(mul(mul(ch(detail,3),rough),2.2),rough))))
    rough=tag(saturate(lerp(rough,adjusted,amount)),'DR.Surface','Native weapon roughness detail')
    outputs={'base_color':c,'normal':composed,'roughness':rough,'metallic':saturate(ch(nxm,3)),'alpha':literal(1.)}
    active=[z for z in ZONES if record.switches.get('Enable '+z+' Mask',False)]
    # The paint stages compile in whenever a zone mask is enabled; UseWeaponQuality only picks the quality source.
    if active:return compile_native_weapon_paint(record,context)
    if active:diagnostics.append('unsupported_native_stage:paint palette/wear permutation '+','.join(active)+'; native base only')
    if record.switches.get('UseWeaponQuality',False):diagnostics.append('unsupported_native_stage:weapon native wear transfer')
    if record.switches.get('Use Opacity',False):diagnostics.append('unsupported_native_stage:weapon opacity permutation')
    if record.switches.get('Use "Glare"',False):diagnostics.append('unsupported_native_stage:weapon glare permutation')
    emission=mapped_channel(record,context,'weapon_emission')
    if emission is not None:
        outputs['emission']=tag(mul(color(record,'Tint Color'),emission),'DR.Light','Bound weapon emission')
        outputs['emission_strength']=scalar(record,'Emissive Power',3.)
    return plan(record,'weapon',outputs,diagnostics,native_shader_mapping='fresh-queryF0FC...3716 NXM+CR+TA_Weapon_Detail_01')


RUST_NORMAL='/Game/Pioneer/MaterialLibrary/Textures/Weapons/Details/T_WeaponRust_Detail_NX'
